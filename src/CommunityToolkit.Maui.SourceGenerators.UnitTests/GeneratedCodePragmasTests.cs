using System.Collections.Immutable;
using System.Text.RegularExpressions;
using CommunityToolkit.Maui.SourceGenerators.Helpers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Xunit;

namespace CommunityToolkit.Maui.SourceGenerators.UnitTests;

public partial class GeneratedCodePragmasTests
{
	const string generatedCodeFilePath = "Generated.g.cs";

	[Fact]
	public void TrimAndAotWarnings_ListsExactlyTheIlCodesTheBuildTreatsAsErrors()
	{
		var warningsAsErrors = GetRepositoryFile("Directory.Build.props");
		var buildPropsIlCodes = IlCodeRegex().Matches(ExtractWarningsAsErrorsBlock(warningsAsErrors)).Select(static match => match.Value).ToList();

		var pragmaCodes = GeneratedCodePragmas.TrimAndAotWarnings.Split(", ").ToList();

		Assert.NotEmpty(buildPropsIlCodes);
		Assert.Equal(buildPropsIlCodes, pragmaCodes);
		Assert.Equal(pragmaCodes.Count, pragmaCodes.Distinct(StringComparer.Ordinal).Count());
	}

	[Fact]
	public async Task Header_KeepsTrimAnalyzerWarningsAndSuppressesEveryOtherWarning()
	{
		var generatedSource = $$"""
			// <auto-generated>
			{{GeneratedCodePragmas.Header}}

			class Generated
			{
				int Field;
			}
			""";
		var compilation = CSharpCompilation.Create(
			"HeaderProbe",
			[CSharpSyntaxTree.ParseText(generatedSource, path: generatedCodeFilePath, cancellationToken: TestContext.Current.CancellationToken)],
			GeneratorCultureTests.GetReferences(),
			new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

		var diagnostics = await compilation
			.WithAnalyzers([new FieldDeclarationProbeAnalyzer()])
			.GetAnalyzerDiagnosticsAsync(TestContext.Current.CancellationToken);

		Assert.Equal([FieldDeclarationProbeAnalyzer.TrimWarningId], diagnostics.Select(static diagnostic => diagnostic.Id));
	}

	static string ExtractWarningsAsErrorsBlock(string buildProps)
	{
		var match = WarningsAsErrorsRegex().Match(buildProps);
		Assert.True(match.Success, "No <WarningsAsErrors> block in Directory.Build.props");
		return match.Groups["codes"].Value;
	}

	static string GetRepositoryFile(string fileName)
	{
		for (var directory = new DirectoryInfo(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
		{
			var candidate = Path.Combine(directory.FullName, fileName);
			if (File.Exists(candidate) && File.Exists(Path.Combine(directory.FullName, "global.json")))
			{
				return File.ReadAllText(candidate);
			}
		}

		throw new FileNotFoundException($"{fileName} was not found in any parent of {AppContext.BaseDirectory}");
	}

	[GeneratedRegex(@"<WarningsAsErrors>(?<codes>.*?)</WarningsAsErrors>", RegexOptions.Singleline)]
	private static partial Regex WarningsAsErrorsRegex();

	[GeneratedRegex(@"\bIL\d{4}\b")]
	private static partial Regex IlCodeRegex();

	// Mirrors the real trim analyzer, which analyzes generated code too and reports on the same node as unrelated analyzers.
	// The test instantiates this analyzer directly, so no compiler ever loads it, and a DiagnosticAnalyzer attribute would trigger the loader-only rules RS1036, RS1038 and RS1041.
#pragma warning disable RS1001
	sealed class FieldDeclarationProbeAnalyzer : DiagnosticAnalyzer
	{
		public const string TrimWarningId = "IL2026";
		const string otherWarningId = "CTMTEST0001";

		// A test-only analyzer is never shipped, so it has no release tracking.
#pragma warning disable RS2008
		static readonly DiagnosticDescriptor trimWarning = new(TrimWarningId, "Trim", "Trim", "Test", DiagnosticSeverity.Warning, true);
		static readonly DiagnosticDescriptor otherWarning = new(otherWarningId, "Other", "Other", "Test", DiagnosticSeverity.Warning, true);
#pragma warning restore RS2008

		public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; } = [trimWarning, otherWarning];

		public override void Initialize(AnalysisContext context)
		{
			context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
			context.EnableConcurrentExecution();
			context.RegisterSyntaxNodeAction(static nodeContext =>
			{
				var location = ((FieldDeclarationSyntax)nodeContext.Node).GetLocation();
				nodeContext.ReportDiagnostic(Diagnostic.Create(trimWarning, location));
				nodeContext.ReportDiagnostic(Diagnostic.Create(otherWarning, location));
			}, SyntaxKind.FieldDeclaration);
		}
	}
#pragma warning restore RS1001
}